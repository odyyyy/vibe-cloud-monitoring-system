package com.monitoring.alerts.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.Instant;

/**
 * A message in the collaboration thread attached to an incident.
 *
 * <p>{@code organizationId} is denormalized so every read can be scoped to the tenant in the
 * query itself. System comments are generated by the platform when a slash command changes the
 * incident lifecycle; they keep the acting user so the UI can attribute the action.
 */
@Entity
@Table(
        name = "incident_comments",
        indexes = {
                @Index(name = "idx_incident_comments_incident_created",
                        columnList = "incident_id, created_at"),
                @Index(name = "idx_incident_comments_organization_id", columnList = "organization_id")
        }
)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class IncidentComment {

    public static final int MAX_TEXT_LENGTH = 2000;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "incident_id", nullable = false)
    private Long incidentId;

    @Column(name = "organization_id", nullable = false)
    private Long organizationId;

    /** Author of the comment; {@code null} for platform-generated messages without an actor. */
    @Column(name = "user_id")
    private Long userId;

    @Column(nullable = false, length = MAX_TEXT_LENGTH)
    private String text;

    @Column(name = "is_system", nullable = false)
    private boolean system;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;
}
