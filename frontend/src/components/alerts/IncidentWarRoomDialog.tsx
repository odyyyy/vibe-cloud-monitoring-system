import { useEffect, useMemo, useState, type FormEvent, type ReactNode } from 'react'
import { Loader2, MessageSquare, Send, ShieldCheck } from 'lucide-react'
import { toast } from 'sonner'
import type { AlertIncident, IncidentComment } from '../../api/alerts'
import { useAddIncidentCommentMutation, useIncidentCommentsQuery } from '../../api/alerts'
import { ApiError } from '../../api/client'
import type { MembershipRole } from '../../store/authStore'
import {
  MAX_INCIDENT_COMMENT_LENGTH,
  parseIncidentComment,
  validateIncidentComment,
} from '../../features/alerts/incidentComments'
import { useCanManage } from '../../features/organizations/useCanManage'
import { formatDateTime } from '../../lib/datetime'
import { Badge } from '../ui/badge'
import { Button } from '../ui/button'
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from '../ui/dialog'
import { Label } from '../ui/label'
import { Skeleton } from '../ui/skeleton'
import { IncidentStatusBadge } from './IncidentStatusBadge'

const COMMENT_PAGE_SIZE = 100
const POLL_INTERVAL_MS = 15_000

const ROLE_LABELS: Record<MembershipRole, string> = {
  OWNER: 'Owner',
  ADMIN: 'Admin',
  VIEWER: 'Viewer',
}

const ROLE_VARIANTS: Record<MembershipRole, 'warning' | 'info' | 'muted'> = {
  OWNER: 'warning',
  ADMIN: 'info',
  VIEWER: 'muted',
}

interface IncidentWarRoomDialogProps {
  incident: AlertIncident | null
  isVisible: boolean
  onClose: () => void
}

/**
 * Incident collaboration thread. Comments are polled while the dialog is open and the browser
 * tab is visible; system comments generated by /acknowledge and /resolve are visually distinct
 * from human messages.
 */
export function IncidentWarRoomDialog({
  incident,
  isVisible,
  onClose,
}: IncidentWarRoomDialogProps) {
  const canManage = useCanManage()
  const [draft, setDraft] = useState('')
  const [error, setError] = useState<string | null>(null)

  const incidentId = incident?.id ?? null
  const commentsQuery = useIncidentCommentsQuery(
    incidentId,
    0,
    COMMENT_PAGE_SIZE,
    isVisible ? POLL_INTERVAL_MS : false,
  )
  const addComment = useAddIncidentCommentMutation(incidentId)

  useEffect(() => {
    setDraft('')
    setError(null)
  }, [incidentId])

  const comments = useMemo(
    () => [...(commentsQuery.data?.content ?? [])].reverse(),
    [commentsQuery.data],
  )

  const submit = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault()
    if (!incident) {
      return
    }
    const value = draft.trim()
    const validationError = validateIncidentComment(value)
    if (validationError) {
      setError(validationError)
      return
    }

    try {
      await addComment.mutateAsync(value)
      setDraft('')
      setError(null)
      toast.success('Comment posted.')
    } catch (submitError) {
      setError(
        submitError instanceof ApiError
          ? submitError.message
          : 'Could not post the comment. Please try again.',
      )
    }
  }

  return (
    <Dialog
      open={incident !== null}
      onOpenChange={(open) => {
        if (!open) {
          onClose()
        }
      }}
    >
      <DialogContent className="max-h-[90vh] max-w-3xl overflow-y-auto">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <MessageSquare className="h-5 w-5 text-cyan-300" aria-hidden="true" />
            Incident war room
          </DialogTitle>
          <DialogDescription>
            {incident ? incident.ruleName : 'Incident discussion'} - coordinate the response,
            share links and update the incident without leaving the thread.
          </DialogDescription>
        </DialogHeader>

        {incident ? (
          <>
            <div className="mt-3 flex flex-wrap items-center gap-2 text-xs text-slate-400">
              <IncidentStatusBadge status={incident.status} />
              <span>Triggered {formatDateTime(incident.triggeredAt)}</span>
              <span aria-hidden="true">-</span>
              <span>
                {isVisible
                  ? 'Refreshes every 15 seconds.'
                  : 'Refresh paused while this tab is hidden.'}
              </span>
            </div>

            <div className="mt-4 space-y-2" role="log" aria-live="polite" aria-busy={commentsQuery.isLoading}>
              {commentsQuery.isLoading ? (
                <div className="space-y-2">
                  <Skeleton className="h-20 w-full rounded-xl" />
                  <Skeleton className="h-20 w-full rounded-xl" />
                </div>
              ) : commentsQuery.isError ? (
                <div role="alert" className="rounded-xl border border-red-500/30 bg-red-500/5 p-4">
                  <p className="text-sm text-red-200">
                    {commentsQuery.error instanceof ApiError
                      ? commentsQuery.error.message
                      : 'Could not load the discussion.'}
                  </p>
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    className="mt-3"
                    onClick={() => void commentsQuery.refetch()}
                    disabled={commentsQuery.isFetching}
                  >
                    Retry
                  </Button>
                </div>
              ) : comments.length === 0 ? (
                <p className="rounded-xl border border-dashed border-white/10 bg-white/[0.02] px-4 py-8 text-center text-sm text-slate-400">
                  No discussion yet. Share what you are seeing so the team has context.
                </p>
              ) : (
                comments.map((comment) => <CommentItem key={comment.id} comment={comment} />)
              )}
            </div>

            <form onSubmit={(event) => void submit(event)} className="mt-5 space-y-2 border-t border-white/10 pt-4">
              <div className="flex items-center justify-between gap-3">
                <Label htmlFor="incident-comment">Message</Label>
                <span className="text-xs text-slate-500">
                  {draft.length}/{MAX_INCIDENT_COMMENT_LENGTH}
                </span>
              </div>
              <textarea
                id="incident-comment"
                value={draft}
                onChange={(event) => {
                  setDraft(event.target.value)
                  setError(null)
                }}
                onKeyDown={(event) => {
                  if (event.key === 'Enter' && (event.ctrlKey || event.metaKey)) {
                    event.currentTarget.form?.requestSubmit()
                  }
                }}
                maxLength={MAX_INCIDENT_COMMENT_LENGTH}
                rows={4}
                placeholder="Investigating now, looks like DB CPU is high."
                aria-invalid={error !== null}
                className="flex w-full rounded-md border border-white/10 bg-canvas-2 px-3 py-2 text-sm text-slate-100 transition-colors placeholder:text-slate-500 focus-visible:border-cyan-400/40 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-cyan-400/50 aria-[invalid=true]:border-red-500/60 aria-[invalid=true]:focus-visible:ring-red-500/40"
              />
              <p className="text-xs text-slate-500">
                Markdown, http(s) links and <code className="text-slate-400">dashboard:123</code>{' '}
                links are supported. Press Ctrl+Enter to post.
              </p>
              {canManage ? (
                <p className="text-xs text-slate-500">
                  Use <code className="text-slate-400">/acknowledge</code> or{' '}
                  <code className="text-slate-400">/resolve</code> to change the incident state.
                </p>
              ) : null}
              {error ? (
                <p role="alert" className="text-xs text-red-300">
                  {error}
                </p>
              ) : null}
              <div className="flex justify-end">
                <Button
                  type="submit"
                  disabled={addComment.isPending || draft.trim().length === 0}
                >
                  {addComment.isPending ? (
                    <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
                  ) : (
                    <Send className="h-4 w-4" aria-hidden="true" />
                  )}
                  {addComment.isPending ? 'Posting...' : 'Post comment'}
                </Button>
              </div>
            </form>
          </>
        ) : null}
      </DialogContent>
    </Dialog>
  )
}

function CommentItem({ comment }: { comment: IncidentComment }) {
  if (comment.system) {
    return (
      <article className="flex gap-3 rounded-xl border border-cyan-400/20 bg-cyan-400/[0.06] px-3 py-3">
        <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-cyan-400/10 text-cyan-200">
          <ShieldCheck className="h-4 w-4" aria-hidden="true" />
        </div>
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-2">
            <span className="text-xs font-semibold uppercase tracking-wide text-cyan-200">
              System action
            </span>
            <span className="text-xs text-slate-500">{formatDateTime(comment.createdAt)}</span>
          </div>
          <p className="mt-1 whitespace-pre-wrap break-words text-sm text-slate-200">
            {comment.text}
          </p>
        </div>
      </article>
    )
  }

  const name = comment.username ?? 'Unknown user'
  return (
    <article className="rounded-xl border border-white/10 bg-white/[0.03] px-3 py-3">
      <div className="flex flex-wrap items-center gap-2">
        <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-white/5 text-xs font-semibold text-slate-200">
          {initials(name)}
        </div>
        <span className="text-sm font-semibold text-cyan-200">{name}</span>
        {comment.role ? (
          <Badge variant={ROLE_VARIANTS[comment.role]}>{ROLE_LABELS[comment.role]}</Badge>
        ) : null}
        <span className="ml-auto text-xs text-slate-500">
          {formatDateTime(comment.createdAt)}
        </span>
      </div>
      <div className="mt-2">
        <CommentBody text={comment.text} />
      </div>
    </article>
  )
}

function CommentBody({ text }: { text: string }) {
  return (
    <div className="whitespace-pre-wrap break-words text-sm text-slate-200">
      {parseIncidentComment(text).map((segment, index): ReactNode => {
        switch (segment.type) {
          case 'strong':
            return <strong key={index}>{segment.value}</strong>
          case 'emphasis':
            return <em key={index}>{segment.value}</em>
          case 'code':
            return (
              <code
                key={index}
                className="rounded bg-canvas-2 px-1 py-0.5 font-mono text-xs text-slate-100"
              >
                {segment.value}
              </code>
            )
          case 'link':
            return (
              <a
                key={index}
                href={segment.href}
                target="_blank"
                rel="noopener noreferrer"
                className="break-all text-cyan-300 underline underline-offset-2 hover:text-cyan-200"
              >
                {segment.value}
              </a>
            )
          case 'dashboard':
            return (
              <a
                key={index}
                href={`/app/dashboards/${segment.dashboardId}`}
                target="_blank"
                rel="noopener noreferrer"
                className="text-cyan-300 underline underline-offset-2 hover:text-cyan-200"
              >
                {segment.value}
              </a>
            )
          default:
            return <span key={index}>{segment.value}</span>
        }
      })}
    </div>
  )
}

function initials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean)
  if (parts.length === 0) {
    return '?'
  }
  if (parts.length === 1) {
    return parts[0].slice(0, 2).toUpperCase()
  }
  return `${parts[0][0]}${parts[1][0]}`.toUpperCase()
}
